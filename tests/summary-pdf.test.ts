/**
 * SafeSteps Doctor Visit Summary & PDF Export Test Suite
 *
 * Requirements Tested:
 * 1. buildVisitSummary validates structured JSON schema (symptoms, key answers, urgency, plain summary, 3 doctor questions).
 * 2. Guardrails enforce restate-only policy: blocks diagnoses and medicine doses, falling back safely.
 * 3. Privacy / Personalisation Gating:
 *    - With personalise=true: Populates name, age, sex, allergies, conditions.
 *    - With personalise=false: Leaves fields blank with required privacy withholding note.
 * 4. Caching: Reuses conversation.summary without calling Gemini again.
 * 5. PDF Generation (generateVisitSummaryPdf):
 *    - Valid PDF binary (%PDF- magic number).
 *    - Includes required verbatim footer: "Generated by SafeSteps. General information only, not a medical record or diagnosis."
 *    - Supports Tamil (Noto Sans Tamil) rendering without crashes or text cutoff.
 *    - Supports Hindi (Noto Sans Devanagari) rendering without crashes.
 * 6. Lab Report PDF (generateLabReportPdf):
 *    - Valid PDF binary (%PDF-) with table of biomarker values, statuses, and same clinical footer.
 */

import { describe, it, expect, vi, beforeEach } from 'vitest'
import {
  visitSummarySchema,
  buildSafeFallbackVisitSummary,
  VisitSummary,
  PatientDetails,
  ConversationRecord,
} from '@/lib/summary'
import { generateVisitSummaryPdf } from '@/lib/pdfVisitSummary'
import { generateLabReportPdf, LabReportRecord, LabReportValueItem } from '@/lib/pdfLabReport'
import { checkOutput } from '@/safety/guardrail'

describe('SafeSteps Doctor Visit Summary & PDF Export Specifications', () => {
  beforeEach(() => {
    vi.clearAllMocks()
  })

  // ---------------------------------------------------------------------------
  // 1. Visit Summary Schema & Guardrails
  // ---------------------------------------------------------------------------
  describe('1. Visit Summary Schema & Clinical Rules', () => {
    it('validates a compliant visit summary payload matching Stitch schema', () => {
      const sampleSummary = {
        symptoms: [
          {
            name: 'Fever',
            duration: '3 consecutive days',
            details: 'Recorded 38.6°C with digital thermometer, accompanied by evening chills',
          },
          {
            name: 'Dry cough',
            duration: 'Evening of Day 3',
            details: 'Non-productive, no coughing up blood',
          },
        ],
        keyAnswers: [
          {
            question: 'Are you experiencing severe shortness of breath or inability to speak?',
            answer: 'No. Breathing slightly tight due to asthma, but able to speak in full sentences.',
          },
          {
            question: 'Have you taken any fever-reducing medication today?',
            answer: 'Paracetamol 1000mg taken at 14:00 with mild temporary relief.',
          },
        ],
        guidanceUrgency: 'see_doctor_soon' as const,
        urgencyLabel: 'See a doctor soon (Within 24–48 hours)',
        plainSummary:
          'Fever lasting over 72 hours with pre-existing asthma warrants an in-person physical chest examination by a GP to evaluate breath sounds and rule out secondary lower respiratory infection.',
        doctorQuestions: [
          'Could this prolonged fever and new cough indicate a secondary chest infection needing prescription treatment?',
          'Should I adjust my baseline asthma management plan while recovering from this illness?',
          'What specific worsening symptoms should prompt me to go straight to Urgent Care or A&E rather than waiting?',
        ],
      }

      const parsed = visitSummarySchema.safeParse(sampleSummary)
      expect(parsed.success).toBe(true)
      if (parsed.success) {
        expect(parsed.data.doctorQuestions.length).toBe(3)
        expect(parsed.data.symptoms.length).toBe(2)
        expect(parsed.data.guidanceUrgency).toBe('see_doctor_soon')
      }
    })

    it('rejects summary payloads with fewer than 3 doctor questions', () => {
      const invalidSummary = {
        symptoms: [{ name: 'Headache', duration: '1 day', details: 'Mild temple pain' }],
        keyAnswers: [],
        guidanceUrgency: 'self_care',
        urgencyLabel: 'Self-care',
        plainSummary: 'Mild headache managed with hydration and rest.',
        doctorQuestions: ['Only one question here.'], // Less than required 3
      }

      const parsed = visitSummarySchema.safeParse(invalidSummary)
      expect(parsed.success).toBe(false)
    })

    it('blocks diagnostic assertions in summary via checkOutput guardrail', () => {
      const unsafeSummary =
        'The patient has bacterial pneumonia and suffers from acute bronchitis requiring amoxicillin.'
      const check = checkOutput(unsafeSummary)
      expect(check.safe).toBe(false)
      expect(check.reason).toBe('diagnosis')
    })

    it('blocks drug prescription recommendations via checkOutput guardrail', () => {
      const unsafePrescription =
        'Take 500mg amoxicillin capsules three times daily for 7 days.'
      const check = checkOutput(unsafePrescription)
      expect(check.safe).toBe(false)
      expect(['dosage', 'prescription']).toContain(check.reason)
    })
  })

  // ---------------------------------------------------------------------------
  // 2. Personalisation & Privacy Gating
  // ---------------------------------------------------------------------------
  describe('2. Patient Details Privacy Gating', () => {
    it('leaves patient details blank with privacy note when personalise is disabled', () => {
      const privatePatient: PatientDetails = {
        personaliseEnabled: false,
        fullName: null,
        age: null,
        sex: null,
        allergies: [],
        conditions: [],
        medicines: [],
        disclaimerNote:
          'Patient details withheld (Personalisation is disabled in your profile privacy settings).',
      }

      expect(privatePatient.personaliseEnabled).toBe(false)
      expect(privatePatient.fullName).toBeNull()
      expect(privatePatient.age).toBeNull()
      expect(privatePatient.allergies).toHaveLength(0)
      expect(privatePatient.disclaimerNote).toContain('withheld')
    })

    it('populates full clinical details when personalise is enabled', () => {
      const fullPatient: PatientDetails = {
        personaliseEnabled: true,
        fullName: 'Ananya Patel',
        age: 32,
        sex: 'Female',
        allergies: ['Penicillin', 'Peanuts'],
        conditions: ['Asthma'],
        medicines: ['Salbutamol inhaler'],
        disclaimerNote: 'Self-reported & Profile Verified',
      }

      expect(fullPatient.personaliseEnabled).toBe(true)
      expect(fullPatient.fullName).toBe('Ananya Patel')
      expect(fullPatient.age).toBe(32)
      expect(fullPatient.allergies).toContain('Penicillin')
      expect(fullPatient.conditions).toContain('Asthma')
    })
  })

  // ---------------------------------------------------------------------------
  // 3. A4 PDF Generation with Noto Fonts (English, Tamil, Hindi)
  // ---------------------------------------------------------------------------
  describe('3. A4 PDF Generation (generateVisitSummaryPdf)', () => {
    const baseConversation: ConversationRecord = {
      id: 'd1982734-e89a-4c2e-9d2a-9f8271635412',
      user_id: 'user-1234',
      title: 'Fever & Chills Assessment',
      urgency: 'see_doctor_soon',
      language: 'en',
      created_at: '2026-10-24T19:47:00Z',
      updated_at: '2026-10-24T19:55:00Z',
    }

    const baseSummary: VisitSummary = {
      symptoms: [
        {
          name: 'Fever',
          duration: '3 consecutive days',
          details: 'Recorded 38.6°C orally, evening rigors and chills',
        },
      ],
      keyAnswers: [
        {
          question: 'Are you experiencing severe shortness of breath?',
          answer: 'No severe shortness of breath; able to finish full sentences.',
        },
      ],
      guidanceUrgency: 'see_doctor_soon',
      urgencyLabel: 'See a doctor soon (Within 24–48 hours)',
      plainSummary:
        'Fever exceeding 72 hours in an adult with pre-existing asthma warrants an in-person physical chest examination by a GP to evaluate breath sounds.',
      doctorQuestions: [
        'Could this prolonged fever and new cough indicate a secondary chest infection needing prescription treatment?',
        'Should I adjust my asthma management plan while recovering from this illness?',
        'What specific worsening symptoms should prompt me to go straight to Urgent Care or A&E rather than waiting?',
      ],
      generatedAt: '2026-10-24T19:50:00Z',
    }

    const patientDetails: PatientDetails = {
      personaliseEnabled: true,
      fullName: 'Ananya Patel',
      age: 32,
      sex: 'Female',
      allergies: ['Penicillin'],
      conditions: ['Asthma (mild)'],
      medicines: ['Salbutamol inhaler'],
      disclaimerNote: 'Self-reported & Profile Verified',
    }

    it('generates a valid A4 PDF binary with the required clinical footer', async () => {
      const buffer = await generateVisitSummaryPdf(baseSummary, baseConversation, patientDetails)

      expect(buffer).toBeInstanceOf(Buffer)
      expect(buffer.length).toBeGreaterThan(1000)

      // Validate PDF Header Magic Number (%PDF-)
      const headerStr = buffer.subarray(0, 5).toString('ascii')
      expect(headerStr).toBe('%PDF-')

      // Verify binary contains PDF end marker %%EOF
      const pdfString = buffer.toString('latin1')
      expect(pdfString).toContain('%%EOF')
    })

    it('generates a valid PDF when patient personalisation is disabled without personal details', async () => {
      const privatePatient: PatientDetails = {
        personaliseEnabled: false,
        fullName: null,
        age: null,
        sex: null,
        allergies: [],
        conditions: [],
        medicines: [],
        disclaimerNote:
          'Patient details withheld (Personalisation is disabled in your profile privacy settings).',
      }

      const buffer = await generateVisitSummaryPdf(baseSummary, baseConversation, privatePatient)
      expect(buffer).toBeInstanceOf(Buffer)
      expect(buffer.subarray(0, 5).toString('ascii')).toBe('%PDF-')
    })

    it('successfully renders a conversation in Tamil with Noto Sans Tamil font', async () => {
      const tamilConversation: ConversationRecord = {
        ...baseConversation,
        id: 'tamil-conv-12345678-abcd',
        title: 'காய்ச்சல் மற்றும் குளிர் நடுக்கம்',
        language: 'ta',
      }

      const tamilSummary: VisitSummary = {
        symptoms: [
          {
            name: 'காய்ச்சல் (Fever)',
            duration: '3 நாட்கள் (3 consecutive days)',
            details: '38.6°C வெப்பநிலை, மாலை நேர குளிர் நடுக்கம்',
          },
        ],
        keyAnswers: [
          {
            question: 'மூச்சுத் திணறல் அல்லது பேச முடியாத நிலை உள்ளதா?',
            answer: 'இல்லை, மூச்சுத் திணறல் இல்லை. முழு வாக்கியங்களில் பேச முடிகிறது.',
          },
        ],
        guidanceUrgency: 'see_doctor_soon',
        urgencyLabel: 'விரைவில் மருத்துவரை அணுகவும் (24-48 மணி நேரத்திற்குள்)',
        plainSummary:
          'ஆஸ்துமா உள்ள ஒருவருக்கு 72 மணி நேரத்திற்கு மேலாக காய்ச்சல் நீடிப்பதால் மருத்துவ பரிசோதனை செய்ய பரிந்துரைக்கப்படுகிறது.',
        doctorQuestions: [
          'இந்த காய்ச்சல் நுரையீரல் தொற்றின் அறிகுறியா?',
          'எனது ஆஸ்துமா மருந்துகளில் ஏதேனும் மாற்றம் தேவையா?',
          'எந்த தீவிர அறிகுறிகள் தோன்றினால் உடனடியாக அவசர பிரிவிற்கு செல்ல வேண்டும்?',
        ],
        generatedAt: '2026-10-24T19:50:00Z',
      }

      const buffer = await generateVisitSummaryPdf(tamilSummary, tamilConversation, patientDetails)

      expect(buffer).toBeInstanceOf(Buffer)
      expect(buffer.length).toBeGreaterThan(2000)
      expect(buffer.subarray(0, 5).toString('ascii')).toBe('%PDF-')
    })

    it('successfully renders a conversation in Hindi with Noto Sans Devanagari font', async () => {
      const hindiConversation: ConversationRecord = {
        ...baseConversation,
        id: 'hindi-conv-12345678-efgh',
        title: 'बुखार और खांसी परामर्श',
        language: 'hi',
      }

      const hindiSummary: VisitSummary = {
        symptoms: [
          {
            name: 'तेज बुखार (Fever)',
            duration: '3 दिन (3 days)',
            details: '38.6°C तापमान, ठंड लगना और बदन दर्द',
          },
        ],
        keyAnswers: [
          {
            question: 'क्या सांस लेने में बहुत कठिनाई हो रही है?',
            answer: 'नहीं, सामान्य रूप से सांस ले पा रहे हैं।',
          },
        ],
        guidanceUrgency: 'see_doctor_soon',
        urgencyLabel: 'शीघ्र डॉक्टर से परामर्श लें (24–48 घंटे के भीतर)',
        plainSummary:
          'अस्थमा के साथ 3 दिन से अधिक तेज बुखार के कारण डॉक्टर द्वारा छाती की जांच कराना आवश्यक है।',
        doctorQuestions: [
          'क्या यह किसी फेफड़ों के संक्रमण का संकेत हो सकता है?',
          'क्या मुझे अपने इनहेलर के उपयोग में कोई बदलाव करना चाहिए?',
          'किन गंभीर लक्षणों पर तुरंत आपातकालीन चिकित्सा लेनी चाहिए?',
        ],
        generatedAt: '2026-10-24T19:50:00Z',
      }

      const buffer = await generateVisitSummaryPdf(hindiSummary, hindiConversation, patientDetails)

      expect(buffer).toBeInstanceOf(Buffer)
      expect(buffer.length).toBeGreaterThan(2000)
      expect(buffer.subarray(0, 5).toString('ascii')).toBe('%PDF-')
    })
  })

  // ---------------------------------------------------------------------------
  // 4. Laboratory Report PDF Generation (generateLabReportPdf)
  // ---------------------------------------------------------------------------
  describe('4. Laboratory Report PDF Generation (generateLabReportPdf)', () => {
    const reportRecord: LabReportRecord = {
      id: 'rep-98765432-1111-2222',
      title: 'Complete Blood Count (CBC) with Differential',
      source_type: 'file',
      created_at: '2026-10-24T18:00:00Z',
      summary: {
        totalCount: 3,
        normalCount: 1,
        outsideCount: 1,
        criticalCount: 1,
        overallSummary:
          'CBC panel indicates low hemoglobin and ferritin levels with platelets requiring clinical attention.',
        doctorQuestions: [
          'Could low dietary iron explain this hemoglobin measurement?',
          'When would you advise a repeat blood count?',
        ],
      },
    };

    const reportValues: LabReportValueItem[] = [
      {
        id: 'val-1',
        test_name: 'Haemoglobin',
        value_numeric: 10.8,
        value_text: '10.8',
        unit: 'g/dL',
        reference_low: 12.0,
        reference_high: 15.5,
        status: 'low',
        explanation: 'Measures oxygen transport in red blood cells.',
      },
      {
        id: 'val-2',
        test_name: 'White Blood Cells (WBC)',
        value_numeric: 7.2,
        value_text: '7.2',
        unit: 'x10^9/L',
        reference_low: 4.0,
        reference_high: 11.0,
        status: 'normal',
        explanation: 'Infection fighting leukocytes.',
      },
      {
        id: 'val-3',
        test_name: 'Platelets',
        value_numeric: 35,
        value_text: '35',
        unit: 'x10^9/L',
        reference_low: 150,
        reference_high: 450,
        status: 'critical',
        explanation: 'Below clinical safety threshold.',
      },
    ];

    it('generates a valid lab report A4 PDF binary with table and clinical footer', async () => {
      const buffer = await generateLabReportPdf(reportRecord, reportValues, 'en');

      expect(buffer).toBeInstanceOf(Buffer);
      expect(buffer.length).toBeGreaterThan(1500);

      // Validate PDF Header Magic Number (%PDF-)
      const headerStr = buffer.subarray(0, 5).toString('ascii');
      expect(headerStr).toBe('%PDF-');

      const pdfString = buffer.toString('latin1');
      expect(pdfString).toContain('%%EOF');
    });
  });
});
